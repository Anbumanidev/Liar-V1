// Safe DOM builder: text is always inserted as text nodes (never innerHTML), so symbols and
// LLM-written text coming from the DB can never inject markup or script.

const SVG_NS = 'http://www.w3.org/2000/svg';

// Native replaceChildren/append/prepend turn null/undefined/booleans into text ("null"). Optional
// pieces are written as `cond ? node : null` throughout the UI, so drop such values centrally
// (and accept nested arrays). Strings are still inserted as text nodes only.
const keep = (n) => n !== null && n !== undefined && n !== false && n !== true;
for (const proto of [Element.prototype, DocumentFragment.prototype]) {
  for (const name of ['replaceChildren', 'append', 'prepend']) {
    const orig = proto[name];
    if (typeof orig !== 'function' || orig.liarSafe) continue;
    const safe = function (...nodes) { return orig.apply(this, nodes.flat(Infinity).filter(keep)); };
    safe.liarSafe = true;
    proto[name] = safe;
  }
}

export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  if (attrs) applyAttrs(el, attrs);
  append(el, children);
  return el;
}

function applyAttrs(el, attrs) {
  for (const [k, v] of Object.entries(attrs)) {
    if (v === null || v === undefined || v === false) continue;
    if (k === 'class' || k === 'className') el.className = Array.isArray(v) ? v.filter(Boolean).join(' ') : v;
    else if (k === 'style' && typeof v === 'object') {
      for (const [p, val] of Object.entries(v)) {
        if (val === null || val === undefined) continue;
        if (p.startsWith('--')) el.style.setProperty(p, val); else el.style[p] = val;
      }
    } else if (k === 'dataset') Object.assign(el.dataset, v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
    else if (k === 'text') el.textContent = String(v);
    else if (k === 'value') el.value = v;
    else if (k === 'checked' || k === 'disabled' || k === 'selected' || k === 'open' || k === 'hidden') el[k] = !!v;
    else if (k === 'html' || k === 'innerHTML') throw new Error('innerHTML is not allowed');
    else el.setAttribute(k, v === true ? '' : String(v));
  }
}

export function append(el, children) {
  for (const c of children.flat(Infinity)) {
    if (c === null || c === undefined || c === false || c === true) continue;
    el.appendChild(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

export function clear(el) {
  while (el.firstChild) el.removeChild(el.firstChild);
  return el;
}

export function replace(el, ...children) {
  clear(el);
  return append(el, children);
}

